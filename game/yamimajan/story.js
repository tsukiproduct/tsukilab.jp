// イカサマ（1局1回）・暴牌・告発を使うと1章78%・2章70%・3章53%の勝率になった。
const STORY_LEVEL=[
  {vigilance:2, cheatRate:0,    gauge:30, accuse:.1,  vetoLimit:0},
  {vigilance:3, cheatRate:.07,  gauge:35, accuse:.3,  vetoLimit:1},
  {vigilance:3, cheatRate:.11,  gauge:45, accuse:.35, vetoLimit:1}
];
// 相手ごとの癖。vig=監視の厳しさ、cheat=イカサマの多さ、tell=イカサマがばれる仕草の出やすさ
const STORY_PERSONA=[
  {vig:0,  cheat:1,    tell:.6},   // 月真猫：気まぐれ
  {vig:1,  cheat:.6,   tell:.5},   // 残：よく見ているが自分ではあまりやらない
  {vig:0,  cheat:1.25, tell:.45},  // 流空：手癖が悪く、隠すのもうまい
  {vig:-1, cheat:1.3,  tell:.85}   // 経経経経減：よそ見しがちで、イカサマが下手
];
function storyDuel(chapter, opponent) {
  const base=STORY_LEVEL[chapter], pe=STORY_PERSONA[opponent];
  return {opponent, vigilance:Math.max(1,Math.min(4,base.vigilance+pe.vig)),
    cheatRate:+(base.cheatRate*pe.cheat).toFixed(3), gauge:base.gauge, accuse:base.accuse,
    vetoLimit:base.vetoLimit, tell:pe.tell};
}

