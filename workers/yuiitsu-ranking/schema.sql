CREATE TABLE IF NOT EXISTS scores (
  pid TEXT NOT NULL,
  diff TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  total REAL NOT NULL,
  t1 REAL NOT NULL, t2 REAL NOT NULL, t3 REAL NOT NULL,
  splits INTEGER NOT NULL DEFAULT 0,
  at INTEGER NOT NULL,
  PRIMARY KEY (pid, diff)
);
CREATE INDEX IF NOT EXISTS scores_rank ON scores (diff, total);
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS hits (ip TEXT PRIMARY KEY, at INTEGER NOT NULL);
